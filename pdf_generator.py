from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from datetime import datetime
import io


def generate_health_report(user_name, risk_tier, probability, recommendations, glucose, bmi, bp, age):
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, topMargin=20 * mm, bottomMargin=20 * mm)
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle('TitleStyle', parent=styles['Title'], fontSize=20, spaceAfter=10)
    heading_style = ParagraphStyle('HeadingStyle', parent=styles['Heading2'], spaceBefore=14, spaceAfter=6)
    normal_style = styles['Normal']

    elements = []

    elements.append(Paragraph("Diabetes Risk Assessment Report", title_style))
    elements.append(Paragraph(f"Generated on: {datetime.now().strftime('%d %B %Y, %H:%M')}", normal_style))
    elements.append(Paragraph(f"Patient Name: {user_name}", normal_style))
    elements.append(Spacer(1, 12))

    elements.append(Paragraph("Risk Summary", heading_style))
    risk_color = colors.red if risk_tier == "High" else (colors.orange if risk_tier == "Medium" else colors.green)
    risk_table = Table([
        ["Risk Level", risk_tier],
        ["Risk Probability", f"{probability}%"]
    ], colWidths=[150, 300])
    risk_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (0, -1), colors.lightgrey),
        ('TEXTCOLOR', (1, 0), (1, 0), risk_color),
        ('FONTNAME', (1, 0), (1, 0), 'Helvetica-Bold'),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.grey),
        ('PADDING', (0, 0), (-1, -1), 8),
    ]))
    elements.append(risk_table)
    elements.append(Spacer(1, 12))

    elements.append(Paragraph("Key Health Parameters", heading_style))
    params_table = Table([
        ["Parameter", "Value"],
        ["Glucose", f"{glucose} mg/dL"],
        ["BMI", f"{bmi}"],
        ["Blood Pressure", f"{bp} mmHg"],
        ["Age", f"{age} years"]
    ], colWidths=[150, 300])
    params_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#4472C4')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.grey),
        ('PADDING', (0, 0), (-1, -1), 8),
    ]))
    elements.append(params_table)
    elements.append(Spacer(1, 12))

    elements.append(Paragraph("Personalized Recommendations", heading_style))
    for tip in recommendations:
        elements.append(Paragraph(f"• {tip}", normal_style))
    elements.append(Spacer(1, 16))

    elements.append(Paragraph(
        "<i>Disclaimer: This report is generated by an AI-based screening tool and is intended for "
        "preventive health awareness only. It does not replace professional medical diagnosis. "
        "Please consult a qualified healthcare provider for further evaluation.</i>",
        normal_style
    ))

    doc.build(elements)
    buffer.seek(0)
    return buffer